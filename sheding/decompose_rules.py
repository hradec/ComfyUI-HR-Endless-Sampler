# MiniMax-H3 分段格式化规则
# ============================
# 直接修改此字符串，重启 ComfyUI 或重新加载工作流即可生效。
# 此文本作为 System Prompt 的 {Decompose_Rules} 占位符注入。

DECOMPOSE_RULES = '''### 拆解原则:
0. 分段是情节段落: 每个分段是一段独立视频, 对应故事的一个完整情节段落(可含多个连续动作), 不是单个动作或单个画面。拆解分的是情节; 分段内部的镜头切换([Shot N])是润色阶段的事, 拆解阶段不用管。
1. 视觉独立性: 每一段必须是一段可独立生成视频的视觉描述。禁止依赖前段或后段才能理解的内容。
2. 时间分配: 开头1-2段建立场景, 中间主体展开冲突/发展, 结尾1-2段收束。
3. 景别递进: 每段标注精确景别(远景→全景→中景→近景→特写), 确保视觉节奏不单调。
4. 运镜标注: 每段标注摄像机运动方式(固定/推/拉/摇/移/跟/升/降), 为AI视频生成提供运镜参考。
5. 角色精确: 每段明确列出出场角色, 用原始角色名。无人分段写"无"。
6. 道具具象: 每段列出关键道具, 用具体的物品名称而非抽象概念(如"一把生锈的青铜钥匙"而非"重要物品")。
7. 动作可视化: 动作描述只写相机能物理拍到的东西——肢体的位置、运动轨迹、表情的变化。禁止写内心独白、抽象情感("他感到悲伤"→"他的眼眶泛红, 嘴角微微下垂, 肩膀塌陷")。动作描述写 1-3 句, 覆盖本段核心动作与结果; 详细画面细节写进 detailed_description, 禁止在此字段重复堆砌。按分段时长分配内容密度: 短段(≤5秒)聚焦 1 个核心动作, 长段(>8秒)可铺 2-3 个连续动作。
8. 光影具名: 标注光源方向(顶光/侧光/逆光/顺光)、光源类型(阳光/月光/灯笼/霓虹/烛光)、色调倾向。
9. 物理接触点: 当出现角色肢体互动时, 必须精确描述物理接触部位(如"角色A右手抓住角色B左肩", 而非"两人扭打")。禁止模糊的肢体交互描述, 防止AI生成时产生肢体融合。
10. 运动轨迹: 每个有动作的角色, 必须描述其在画面中的移动方向和速度感(如"从左向右疾跑""原地旋转跃起""缓缓从蹲姿站起")。

### 拆解禁止:
- 禁止生成纯对话分段(无视觉内容的对白). 每段必须有可见的视觉变化.
- 禁止超过2个角色同时出现在同一段中(除非故事风格要求群体场景).
- 禁止模糊的"继续""延续"等跨镜引用词.
- 禁止新增原文不存在的剧情/情节/事件/角色/场景/道具/对话: 拆解=按情节分段, 不是创作/扩写/续写.
- 禁止脑补台词: 原文无对白则无对白, 原文台词必须原样保留; 禁止新增内心独白/画外音/语气词(嗯/啊/哈/笑).
- 原文内容不足时, 只允许在原文已有内容上补充可见细节(外观/动作/光影/环境), 严禁编造新剧情或新对白.
- 动作描述禁止写成流水账或剧情梗概: 1-3 句点到为止, 详细画面细节交给 detailed_description.'''
